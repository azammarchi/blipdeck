let currentLanguage = DEFAULT_LANGUAGE;

function t(key, vars = {}) {
  const str = LANGUAGES[currentLanguage].strings[key] ?? LANGUAGES[DEFAULT_LANGUAGE].strings[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

// Fills every data-i18n* element inside `root` (a document, element or
// template fragment) with the current language.
function translate(root) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}

function setLanguage(code) {
  currentLanguage = LANGUAGES[code] ? code : DEFAULT_LANGUAGE;
  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = LANGUAGES[currentLanguage].dir || 'ltr';
  return currentLanguage;
}
